"""Build assets/network.js from an Overpass export of Wiener Linien route relations.

Usage: python3 tools/build_network.py lines.json > assets/network.js
The Overpass query used is in tools/overpass_query.txt.
"""
import json, math, sys

PICK = {  # line -> relation id (one direction is enough for drawing)
    "U1": 22494, "U3": 20309, "U4": 5954448, "U6": 2853012, "D": 1918957, "37": 2294969,
}

def dist(a, b):
    kx = 111320 * math.cos(math.radians(48.2))
    return math.hypot((a[0]-b[0])*110540, (a[1]-b[1])*kx)

def stitch(ways):
    line = []
    for w in ways:
        g = [(p["lat"], p["lon"]) for p in w]
        if not line:
            line = g; continue
        # orient this way to connect to the current line end
        cands = [(dist(line[-1], g[0]), False, False), (dist(line[-1], g[-1]), True, False),
                 (dist(line[0], g[-1]), False, True), (dist(line[0], g[0]), True, True)]
        d, rev, prepend = min(cands)
        if len(line) == len(ways[0]) and prepend:  # allow flipping the first way
            line = line[::-1]; d, rev, prepend = min(cands[:2])
        if rev: g = g[::-1]
        if d > 400:  # gap (e.g. depot spur) - still connect, it's schematic at that point
            pass
        line = (g + line) if prepend else (line + g)
    return line

def rdp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]
    def perp(p):
        if a == b: return dist(p, a)
        kx = 111320 * math.cos(math.radians(48.2))
        ax, ay = a[1]*kx, a[0]*110540; bx, by = b[1]*kx, b[0]*110540; px, py = p[1]*kx, p[0]*110540
        return abs((bx-ax)*(ay-py) - (ax-px)*(by-ay)) / math.hypot(bx-ax, by-ay)
    i, dm = max(((i, perp(p)) for i, p in enumerate(pts[1:-1], 1)), key=lambda t: t[1])
    if dm > eps:
        return rdp(pts[:i+1], eps)[:-1] + rdp(pts[i:], eps)
    return [a, b]

data = json.load(open(sys.argv[1]))
rels = {r["id"]: r for r in data["elements"]}
out = {}
for ref, rid in PICK.items():
    r = rels[rid]
    ways = [m["geometry"] for m in r["members"] if m["type"] == "way" and m["role"] in ("", "forward", "backward") and "geometry" in m]
    line = rdp(stitch(ways), 6)
    stops = [[round(m["lat"], 5), round(m["lon"], 5)] for m in r["members"] if m["type"] == "node" and m["role"].startswith("stop")]
    out[ref] = {"name": r["tags"].get("name"), "path": [[round(a, 5), round(b, 5)] for a, b in line], "stops": stops}

print("// Generated by tools/build_network.py from OpenStreetMap data (c) OpenStreetMap contributors, ODbL.")
print("window.NETWORK = " + json.dumps(out, separators=(",", ":")) + ";")
